import re
from datetime import datetime
from enum import Enum
from typing import Optional
from pydantic import BaseModel, Field, field_validator


class CategoryEnum(str, Enum):
    RESEARCH_PAPERS = "Research & Papers"
    INDUSTRY_MODELS = "Industry & Models"
    INFRASTRUCTURE_TOOLS = "Infrastructure & Tools"
    POLICY_ETHICS = "Policy & Ethics"


class StoryItem(BaseModel):
    title: str = Field(..., description="Concise, informative headline generated by track")
    original_title: Optional[str] = Field(default=None, description="Original raw headline as published")
    published_date_str: Optional[str] = Field(default=None, description="Formatted publication date (e.g. Sept. 8, 2026)")
    url: str = Field(..., description="Canonical source URL")
    category: CategoryEnum = Field(..., description="Standardized topic category")
    summary: str = Field(..., description="High-signal technical summary (2-3 sentences)")
    source: str = Field(..., description="Publisher or origin")
    published_at: Optional[datetime] = Field(default=None, description="Publication timestamp")
    upvotes: int | None = None

    @field_validator("category", mode="before")
    @classmethod
    def normalize_category(cls, value: str) -> str:
        if not isinstance(value, str):
            return CategoryEnum.INDUSTRY_MODELS.value

        v = value.strip().lower()
        if any(w in v for w in ["paper", "research", "arxiv", "study", "academic"]):
            return CategoryEnum.RESEARCH_PAPERS.value
        elif any(w in v for w in ["tool", "infra", "framework", "library", "hardware", "deploy", "chip"]):
            return CategoryEnum.INFRASTRUCTURE_TOOLS.value
        elif any(w in v for w in ["policy", "law", "ethics", "copyright", "regulation", "safety"]):
            return CategoryEnum.POLICY_ETHICS.value
        else:
            return CategoryEnum.INDUSTRY_MODELS.value


class TrackOutput(BaseModel):
    track_name: str = Field(..., description="'Track A' or 'Track B'")
    stories: list[StoryItem] = Field(..., max_length=5, description="Top 5 verified stories")
    deep_dive: Optional[str] = Field(
        default=None,
        description="~200-word architectural deep-dive (Track B only)",
    )


class RawCandidate(BaseModel):
    title: str
    url: str
    source: str
    published_at: datetime
    raw_text: str
    score: float = 0.0
